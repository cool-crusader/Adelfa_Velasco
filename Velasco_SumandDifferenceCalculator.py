number_1 = int(input("Enter first number: "))
number_2 = int(input("Enter second number: "))

def calculate_sum(number_1, number_2):
    print(f"Sum of {number_1} and {number_2} is {number_1 + number_2}")

def calculate_difference(number_1, number_2):
    print(f"Difference of {number_1} and {number_2} is {number_1 - number_2}")

calculate_sum(number_1, number_2)
calculate_difference(number_1, number_2)